password_gate()

st.title("Parse → chunk → search")
st.caption("A personal hobby project for learning how retrieval pipelines work, built on turbopuffer. "
           "Not affiliated with turbopuffer. The sample handbook and company are fictional.")

with st.sidebar:
    st.header("Document")
    up = st.file_uploader("Upload a PDF (or use the sample)", type=["pdf"])
    if up is not None:
        ss["pdf_name"], ss["pdf"] = up.name, up.getvalue()
    elif "pdf" not in ss:
        ss["pdf_name"], ss["pdf"] = SAMPLE.name, SAMPLE.read_bytes()
    st.write(f"Using **{ss['pdf_name']}**")
    ss["doc_id"] = search.doc_id_for(ss["pdf_name"], ss["pdf"])
    st.divider()
    st.header("Keys")
    st.write("turbopuffer: " + ("✅" if os.getenv("TURBOPUFFER_API_KEY") else "❌ not set"))
    st.write("Claude (optional): " + ("✅" if os.getenv("ANTHROPIC_API_KEY") else "not set"))
    st.caption(f"Region `{search.REGION}` · embedding `{search.EMBED_MODEL}`")
    if st.button("Log out"):
        ss.clear()
        st.rerun()
    st.divider()
    if st.button("Delete this app's namespaces"):
        t = tpuf_or_none()
        if t:
            st.success(f"Deleted {search.delete_demo_namespaces(t)} namespaces.")
            ss.pop("uploaded", None)

t_parse, t_chunk, t_store, t_search = st.tabs(["1 · Parse", "2 · Chunk", "3 · Store", "4 · Search"])

# --- 1. Parse ----------------------------------------------------------------
with t_parse:
    st.markdown("Parsing turns a PDF into text with its structure intact. Compare the naive extraction on the "
                "left with a structured parser on the right: headings, tables, line wraps, and the running "
                "header and footer that would otherwise end up in every chunk.")
    engines = [e for e in parse.available_engines() if e != "raw"]
    if not engines:
        # Keep going with raw text so the rest of the app still works, but say why.
        why = parse.missing_reasons().get("pymupdf", "unknown error")
        st.warning("No structured parser could be loaded, so this falls back to raw text "
                   f"(chunks won't have headings).\n\nReason: `{why}`\n\n"
                   "Fix: `pip install -r requirements.txt` (it needs the `pymupdf` package).")
        engines = ["raw"]
    engine = st.radio("Structured parser", engines, format_func=lambda e: parse.ENGINES[e], horizontal=True)
    if ss.get("parsed_key") != (ss["doc_id"], engine):
        with st.spinner(f"Parsing with {engine}…"):
            ss["parsed"] = parse.parse(ss["pdf"], engine)
            ss["parsed_key"] = (ss["doc_id"], engine)
    p = ss["parsed"]
    c1, c2 = st.columns(2)
    c1.subheader("Raw text (pypdf)")
    c1.code(p["raw"], language=None, wrap_lines=True, height=520)
    c2.subheader(f"Clean Markdown ({engine})")
    c2.code(p["markdown"], language="markdown", wrap_lines=True, height=520)
    if p["removed"]:
        with st.expander(f"Removed {len(p['removed'])} repeated header/footer lines"):
            st.write(p["removed"])
    st.info("Look closely at page 2, which has two columns: the parser can read them in the wrong order. "
            "With the sample, the paragraph about the espresso machine may land under Travel instead of Expenses. "
            "Parsers make mistakes; always check their output before blaming search.")

# --- 2. Chunk ----------------------------------------------------------------
with t_chunk:
    md = ss["parsed"]["markdown"]
    st.markdown("The same Markdown, split two ways. **Recursive** cuts at headings first, then paragraphs and "
                "sentences until pieces fit. **Semantic** ignores headings, embeds every sentence, and cuts where "
                "neighbouring sentences stop being similar.")
    a, b, c, d, e = st.columns(5)
    size = a.slider("Recursive: max chars", 200, 2000, 800, 50)
    overlap = b.slider("Recursive: overlap chars", 0, 300, 100, 10)
    pct = c.slider("Semantic: cut at lowest % of gaps", 5, 50, 20, 5)
    max_sem = d.slider("Semantic: max chars", 400, 3000, 1500, 100)
    ctx = e.toggle("Prepend heading path", value=True,
                   help="Store each chunk with its section path in front, so it keeps its context once cut out.")
    with st.spinner("Chunking…"):
        ss["chunks"] = {
            "recursive": chunk.recursive_chunks(md, size, overlap, ctx),
        }
        sem, gaps = chunk.semantic_chunks(md, pct, max_sem, 200, ctx)
        ss["chunks"]["semantic"], ss["gaps"] = sem, gaps
    left, right = st.columns(2)
    for col, name in ((left, "recursive"), (right, "semantic")):
        s = chunk.summary(ss["chunks"][name])
        col.subheader(name.capitalize())
        m1, m2, m3 = col.columns(3)
        m1.metric("Chunks", s["chunks"])
        m2.metric("Avg chars", s["avg_chars"])
        m3.metric("Span >1 section", s["span_sections"])
        col.markdown(chunk_cards(ss["chunks"][name]), unsafe_allow_html=True)
    with st.expander("Why semantic cut where it did: similarity between neighbouring sentences"):
        g = pd.DataFrame(ss["gaps"])
        if not g.empty:
            g.insert(0, "gap", range(len(g)))
            st.bar_chart(g.set_index("gap")["similarity"])
            st.dataframe(g[["gap", "similarity", "cut", "reason", "cross_section", "after", "before"]],
                         hide_index=True, width="stretch")
            st.caption("A low bar means the next sentence is about something else. 'cross_section' marks gaps "
                       "where a heading sat in the original document, which semantic chunking never sees.")

# --- 3. Store ----------------------------------------------------------------
with t_store:
    st.markdown("Each strategy gets its own **namespace**. turbopuffer creates a namespace on its first write, "
                "embeds the `content` field itself (native embedding), and builds a BM25 index on the same field.")
    if "chunks" not in ss:
        st.info("Open the Chunk tab first.")
    else:
        rows = {k: [c.to_row(ss["doc_id"]) for c in v] for k, v in ss["chunks"].items()}
        st.write("One row as it will be written:")
        st.json(rows["recursive"][0] if rows["recursive"] else {})
        st.code('ns.write(\n    upsert_rows=rows,\n    distance_metric="cosine_distance",\n'
                f'    schema={search.SCHEMA!r},\n)', language="python")
        if st.button("Write both strategies to turbopuffer", type="primary"):
            t = tpuf_or_none()
            if t:
                with st.spinner("Embedding and writing…"):
                    ss["uploaded"] = {k: search.upload(t, ss["doc_id"], k, v) for k, v in rows.items()}
        if ss.get("uploaded"):
            st.success("Written. New data is searchable right away.")
            st.table(pd.DataFrame(ss["uploaded"].values(), index=ss["uploaded"].keys()))

# --- 4. Search ---------------------------------------------------------------
with t_search:
    if not ss.get("uploaded"):
        st.info("Write the chunks on the Store tab first. (If you wrote them in an earlier session, "
                "click the button there again; it's quick.)")
    else:
        pick = st.selectbox("Example questions", ["(type your own below)"] + EXAMPLES)
        q = st.text_input("Question", value="" if pick.startswith("(") else pick)
        c1, c2, c3 = st.columns([2, 2, 1])
        view = c1.radio("Compare", ["Search modes (one strategy)", "Chunking strategies (one mode)"])
        strategy = c2.radio("Strategy", ["recursive", "semantic"], horizontal=True,
                            disabled=view.startswith("Chunking"))
        mode = c2.radio("Mode", search.MODES, index=2, horizontal=True, disabled=view.startswith("Search"))
        top_k = c3.number_input("Top k", 1, 10, 4)
        if q:
            t = tpuf_or_none()
            if t:
                pairs = ([(strategy, m) for m in ("vector", "keyword", "hybrid")] if view.startswith("Search")
                         else [(s, mode) for s in ("recursive", "semantic")])
                cols = st.columns(len(pairs))
                results = {}
                for col, (s, m) in zip(cols, pairs):
                    try:
                        r = search.search(t, ss["doc_id"], s, q, m, int(top_k))
                    except Exception as e:
                        col.error(str(e)[:300])
                        continue
                    results[(s, m)] = r
                    col.subheader(f"{s} · {m}")
                    col.caption(f"{r['ms']} ms round trip")
                    if r["note"]:
                        col.warning(r["note"])
                    col.dataframe(results_table(r["rows"]), hide_index=True, width="stretch")
                    with col.expander("SDK call"):
                        st.code(r["code"], language="python")

                if results:
                    best_key = ("recursive", "hybrid") if ("recursive", "hybrid") in results else next(iter(results))
                    best = results[best_key]
                    st.divider()
                    left, right = st.columns(2)
                    with left:
                        st.markdown(f"**Small to big** · neighbours of the top `{best_key[0]} · {best_key[1]}` hit")
                        if best["rows"]:
                            top = best["rows"][0]
                            for n in search.expand(t, ss["doc_id"], best_key[0], int(top.get("chunk_index", 0))):
                                st.caption(f"chunk {n.get('chunk_index')} · {n.get('section', '')}")
                                st.write(n.get("content", ""))
                    with right:
                        st.markdown(f"**Answer** from the top `{best_key[0]} · {best_key[1]}` chunks")
                        if not os.getenv("ANTHROPIC_API_KEY"):
                            st.caption("Add ANTHROPIC_API_KEY to have Claude write an answer with citations.")
                        elif st.button("Ask Claude"):
                            with st.spinner("Writing…"):
                                try:
                                    st.write(search.answer(q, best["rows"]))
                                except Exception as e:
                                    st.error(str(e)[:300])
