# variables so the pipeline modules can read everything the same way.
try:
    for _k, _v in st.secrets.items():
        if isinstance(_v, (str, int, float)):
            os.environ.setdefault(_k, str(_v))
except Exception:
    pass  # no secrets file, e.g. running locally with environment variables

from pipeline import chunk, parse, search  # noqa: E402  (after secrets are loaded)

SAMPLE = Path(__file__).parent / "samples" / "harbor-lane-handbook.pdf"
ss = st.session_state

# Questions picked to show where each choice wins. See the README's demo script.
