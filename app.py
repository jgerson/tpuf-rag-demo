def password_gate():
    """
    Always on. The app writes to your turbopuffer account, so nobody gets in
    without APP_PASSWORD. If it isn't set, show how to set it instead of
    opening the app. Hobby-grade protection: one shared password, kept for
    the browser session, not a real login system.
    """
    if ss.get("authed"):
        return
    st.title("Parse → chunk → search")
    st.caption("A personal hobby project. Not affiliated with turbopuffer.")
    pw = os.getenv("APP_PASSWORD")
    if not pw:
        st.warning("This app needs a password before it will open.")
        st.markdown(
            "Set `APP_PASSWORD`, then reload:\n\n"
            "- **Running locally:** add `APP_PASSWORD=choose-one` to your `.env` file and load it "
            "(`set -a; source .env; set +a`) before `streamlit run app.py`.\n"
            "- **Streamlit Community Cloud:** App settings → Secrets → add `APP_PASSWORD = \"choose-one\"`, "
            "then reboot the app."
        )
        st.stop()
    with st.form("login"):
        entered = st.text_input("Password", type="password")
        submitted = st.form_submit_button("Enter")
    if submitted:
        # compare_digest avoids leaking how many characters matched via timing
        if hmac.compare_digest(entered.encode(), pw.encode()):
            ss["authed"] = True
            st.rerun()
        st.error("That's not it.")
    st.stop()


# Soft, translucent colours so chunk text stays readable in light and dark mode.
PALETTE = ["rgba(127,119,221,.18)", "rgba(29,158,117,.18)", "rgba(216,90,48,.18)", "rgba(55,138,221,.18)"]


def chunk_cards(chunks: list[chunk.Chunk]) -> str:
    """Render chunks as coloured blocks with their section label."""
    out = []
    for c in chunks:
        bg = PALETTE[c.index % len(PALETTE)]
        label = html.escape(" + ".join(s for s in c.sections if s) or "(no heading)")
        span = " · spans sections" if len(c.sections) > 1 else ""
        body = html.escape(c.text).replace("\n", "<br>")
        out.append(
            f'<div style="background:{bg};border-radius:8px;padding:8px 10px;margin:0 0 8px;font-size:13px;line-height:1.5">'
            f'<div style="opacity:.7;font-size:12px;margin-bottom:4px">#{c.index} · {len(c.text)} chars · {label}{span}</div>'
            f"{body}</div>"
        )
    return "\n".join(out)


def tpuf_or_none():
    try:
        return search.client()
    except Exception as e:
        st.warning(f"turbopuffer isn't configured: {e}")
        return None


def results_table(rows: list[dict]) -> pd.DataFrame:
    return pd.DataFrame([
        {"#": i, "score": r.get("score"), "section": r.get("section", ""), "chunk": r.get("chunk_index"),
         "text": (r.get("content") or "")[:260]}
        for i, r in enumerate(rows, 1)
    ])


