"""
Parse, chunk, search: a hobby demo built on turbopuffer
=======================================================

A personal hobby project I built to learn how document retrieval pipelines
work end to end. It is not affiliated with or endorsed by turbopuffer, and
it is not production code.

The app walks one document through four stages, one tab each:

  1. Parse    PDF -> clean Markdown, next to the naive raw-text version
  2. Chunk    the same Markdown split two ways: structure-aware recursive
              vs semantic, colour-coded so you can see where each one cuts
  3. Store    both sets of chunks written to turbopuffer, which embeds them
  4. Search   vector, keyword (BM25), hybrid and reranked search side by
              side, plus an optional Claude answer with citations

The sample document is a fictional employee handbook generated by
scripts/make_sample_pdf.py.

Secrets (environment variables, or Streamlit Cloud: App settings -> Secrets)
  TURBOPUFFER_API_KEY   required for stages 3 and 4
  ANTHROPIC_API_KEY     optional, enables the written answer
  APP_PASSWORD          optional, protects the page if you deploy it
"""

