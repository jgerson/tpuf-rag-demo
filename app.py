ACTOR_ICON = {"user": "👤", "app → turbopuffer": "🐡", "app → Claude": "➡️", "Claude → app": "💬",
              "tool (local)": "📑"}


def show_run(col, run: agent.Run):
    m1, m2, m3, m4 = col.columns(4)
    m1.metric("LLM turns", run.llm_turns)
    m2.metric("turbopuffer queries", run.tpuf_queries)
    m3.metric("Search time", f"{run.tpuf_ms} ms")
    m4.metric("Tokens in / out", f"{run.input_tokens:,} / {run.output_tokens:,}")
    col.caption(f"{run.seconds} s end to end, mostly LLM time.")
    col.markdown("**Answer**")
    col.info(run.answer or "(no answer)")
    if run.note:
        col.warning(run.note)
    col.markdown("**Step by step**")
    for n, s in enumerate(run.steps, 1):
        ms = f" · {s.ms} ms" if s.ms is not None else ""
        with col.expander(f"{n}. {ACTOR_ICON.get(s.actor, '•')} {s.actor} · {s.title}{ms}", expanded=False):
            if s.sent:
                st.caption("Sent")
                st.code(s.sent, language=None, wrap_lines=True)
            if s.received:
                st.caption("Received")
                st.code(s.received, language=None, wrap_lines=True)
            if s.why:
                st.caption("Why the next step happens")
                st.write(s.why)


